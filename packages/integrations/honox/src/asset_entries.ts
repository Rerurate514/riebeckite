import fs from "node:fs";
import path from "node:path";
import type { ResolvedRiebeckiteConfig } from "@riebeckite/core";

type GeneratedAssetPaths = {
  frameworkStyles: string;
  pluginStyles: string;
  themeStyles: string;
};

type UniqueStrings = (values: string[]) => string[];

export async function writeRiebeckiteAssetEntries(
  config: ResolvedRiebeckiteConfig,
  paths: GeneratedAssetPaths,
): Promise<void> {
  const { uniqueStrings } = await import("@riebeckite/core");
  writeGeneratedFile(
    paths.frameworkStyles,
    createFrameworkStylesEntry(uniqueStrings),
  );
  writeGeneratedFile(
    paths.pluginStyles,
    createPluginStylesEntry(config, uniqueStrings),
  );
  writeGeneratedFile(
    paths.themeStyles,
    createThemeStylesEntry(config, uniqueStrings),
  );
}

function createFrameworkStylesEntry(uniqueStrings: UniqueStrings): string {
  return createStylesheetEntry(
    uniqueStrings,
    ["@riebeckite/honox/style.css"],
    "Framework structural styles. Generated by @riebeckite/honox; do not edit. Import this before the plugin and theme stylesheets.",
  );
}

function createPluginStylesEntry(
  config: ResolvedRiebeckiteConfig,
  uniqueStrings: UniqueStrings,
): string {
  return createStylesheetEntry(
    uniqueStrings,
    collectPluginStyleSpecifiers(config),
    "Plugin default styles in the rb-plugins cascade layer, in resolved plugin order. Generated by @riebeckite/honox; do not edit.",
    "rb-plugins",
  );
}

function createThemeStylesEntry(
  config: ResolvedRiebeckiteConfig,
  uniqueStrings: UniqueStrings,
): string {
  return createStylesheetEntry(
    uniqueStrings,
    config.theme.styles.map((style) => style.moduleSpecifier),
    "Theme styles in the rb-theme cascade layer. Generated by @riebeckite/honox; do not edit.",
    "rb-theme",
  );
}

function collectPluginStyleSpecifiers(
  config: ResolvedRiebeckiteConfig,
): string[] {
  return config.plugins.flatMap((plugin) =>
    (plugin.assets ?? [])
      .filter((asset) => asset.kind === "style")
      .map((asset) => asset.moduleSpecifier),
  );
}

function createStylesheetEntry(
  uniqueStrings: UniqueStrings,
  moduleSpecifiers: string[],
  banner?: string,
  layer?: string,
): string {
  const imports = uniqueStrings(moduleSpecifiers)
    .map(
      (specifier) =>
        `@import ${JSON.stringify(specifier)}${layer ? ` layer(${layer})` : ""};`,
    )
    .join("\n");
  if (!banner) return imports;
  const header = `/* ${banner.replace(/\*\//g, "* /")} */`;
  return imports ? `${header}\n${imports}\n` : `${header}\n`;
}

function writeGeneratedFile(filePath: string, contents: string): void {
  if (readGeneratedFile(filePath) === contents) return;
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

function readGeneratedFile(filePath: string): string | undefined {
  try {
    return fs.readFileSync(filePath, "utf8");
  } catch (error) {
    if (isNotFoundError(error)) return undefined;
    throw error;
  }
}

function isNotFoundError(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    error.code === "ENOENT"
  );
}
